// Regenerates the committed third-party bundles under client/vendor/ and server/vendor/.
//
// Paseo compiles plugins with esbuild on the daemon and bundles whatever node_modules
// contains, but a Git install runs no package manager. So the plugin ships prebuilt,
// self-contained copies of its dependencies and this script is the only way they change:
//
//   client/vendor/viewer-engine.js   engine/ + three.js (MIT), one ESM file, no imports
//   server/vendor/occt-import-js.js  occt-import-js Emscripten glue (LGPL-2.1), verbatim
//   server/vendor/occt-wasm.js       occt-import-js.wasm, brotli-compressed, base64
//
// Run `npm run build:vendor` after changing engine/ or upgrading three / occt-import-js,
// and `npm run check:vendor` (also part of `npm test`) to confirm the committed files match.
import { build } from "esbuild";
import { createRequire } from "node:module";
import { brotliCompressSync, constants } from "node:zlib";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(root, "package.json"));
const check = process.argv.includes("--check");

// three's "exports" hides package.json, so walk up from its entry point instead.
function packageDir(name) {
  for (let directory = dirname(require.resolve(name)); ; directory = dirname(directory)) {
    try {
      if (JSON.parse(readFileSync(join(directory, "package.json"), "utf8")).name === name) return directory;
    } catch {}
    if (dirname(directory) === directory) throw new Error(`Cannot find the ${name} package`);
  }
}
const occtDir = packageDir("occt-import-js");
const occtDist = join(occtDir, "dist");
const threeDir = packageDir("three");
const occtVersion = JSON.parse(readFileSync(join(occtDir, "package.json"), "utf8")).version;
const threeVersion = JSON.parse(readFileSync(join(threeDir, "package.json"), "utf8")).version;

async function engineBundle() {
  const result = await build({
    entryPoints: [join(root, "engine/index.ts")],
    bundle: true,
    format: "esm",
    // Paseo re-bundles this file for React Native's Hermes and the browser; es2020 matches
    // the target its own client compiler uses.
    target: "es2020",
    platform: "neutral",
    mainFields: ["module", "main"],
    minify: true,
    legalComments: "none",
    write: false,
    logLevel: "silent",
  });
  const banner =
    `// Generated by scripts/build-vendor.mjs from engine/ - do not edit.\n` +
    `// Bundles three.js ${threeVersion} (MIT License, Copyright three.js authors,\n` +
    `// https://github.com/mrdoob/three.js). See THIRD_PARTY_NOTICES.md.\n`;
  return banner + result.outputFiles[0].text;
}

function wasmModule() {
  const wasm = readFileSync(join(occtDist, "occt-import-js.wasm"));
  const compressed = brotliCompressSync(wasm, {
    params: {
      [constants.BROTLI_PARAM_QUALITY]: 11,
      [constants.BROTLI_PARAM_SIZE_HINT]: wasm.length,
    },
  });
  // The plugin subprocess cannot locate files next to its bundle (Paseo evaluates the
  // compiled bundle from a string), so the wasm travels inside the bundle itself.
  return (
    `// Generated by scripts/build-vendor.mjs - do not edit.\n` +
    `// occt-import-js ${occtVersion} occt-import-js.wasm (LGPL-2.1, https://github.com/kovacsv/occt-import-js),\n` +
    `// brotli-compressed and base64-encoded. Unmodified; see server/vendor/LICENSE.occt-import-js.txt.\n` +
    `export const wasmByteLength = ${wasm.length};\n` +
    `export const wasmBrotliBase64 =\n  "${compressed.toString("base64")}";\n`
  );
}

const outputs = new Map([
  ["client/vendor/viewer-engine.js", await engineBundle()],
  ["server/vendor/occt-wasm.js", wasmModule()],
  ["server/vendor/occt-import-js.js", readFileSync(join(occtDist, "occt-import-js.js"), "utf8")],
  ["server/vendor/LICENSE.occt-import-js.txt", readFileSync(join(occtDist, "license.occt-import-js.txt"), "utf8")],
  ["server/vendor/LICENSE.occt.txt", readFileSync(join(occtDist, "license.occt.txt"), "utf8")],
  ["client/vendor/LICENSE.three.txt", readFileSync(join(threeDir, "LICENSE"), "utf8")],
]);

let stale = 0;
for (const [relative, contents] of outputs) {
  const target = join(root, relative);
  if (check) {
    let current = null;
    try {
      current = readFileSync(target, "utf8");
    } catch {}
    if (current !== contents) {
      console.error(`stale: ${relative}`);
      stale++;
    }
    continue;
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, contents);
  console.log(`wrote ${relative} (${(Buffer.byteLength(contents) / 1024).toFixed(0)} KiB)`);
}
if (check) {
  if (stale) {
    console.error("Vendored files are out of date. Run `npm run build:vendor`.");
    process.exit(1);
  }
  console.log("Vendored files are up to date.");
}
